// ─── current language (initialised by IIFE below) ───────────────────────────
let currentLang = 'fr';

// ─── applyLang ───────────────────────────────────────────────────────────────
function applyLang(lang) {
  currentLang = lang;
  const t = TRANSLATIONS[lang];

  // 1. data-i18n attributes (innerHTML so <br> works)
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.innerHTML = t[key];
  });

  // 2. Toggle button label
  const btn = document.getElementById('langToggleBtn');
  if (btn) btn.textContent = lang === 'fr' ? 'FR | EN' : 'EN | FR';
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key] !== undefined) el.setAttribute('placeholder', t[key]);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(function(el) {
    const key = el.getAttribute('data-i18n-title');
    if (t[key] !== undefined) el.setAttribute('title', t[key]);
  });

  // 3. <html lang> attribute
  document.documentElement.lang = lang === 'fr' ? 'fr-CI' : 'en';

  // Keep the ID label and computed monthly amounts in the selected language.
  document.querySelectorAll('.card-id').forEach(function(el) {
    const id = el.dataset.customerId || '';
    const missing = t.offers_id_missing || '—';
    el.textContent = (t.offers_id_label || 'ID number: —').replace('—', id || missing);
  });
  if (typeof updateMonthlyPayments === 'function') updateMonthlyPayments();
  if (typeof updateIvoryCoastTime === 'function') updateIvoryCoastTime();

  // Save the language preference.
  localStorage.setItem('swiftloan_lang', lang);
}

// ─── toggleLang ─────────────────────────────────────────────────────────────
function toggleLang() {
  applyLang(currentLang === 'en' ? 'fr' : 'en');
}

// ─── Auto-init: respect saved preference, default to French ─────────────────
(function() {
  var saved = localStorage.getItem('swiftloan_lang');
  applyLang(saved === 'en' ? 'en' : 'fr');
})();
